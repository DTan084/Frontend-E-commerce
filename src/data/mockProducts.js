export const getAllProducts = () => mockProducts;

export const getProductById = (id) => {
  return mockProducts.find(p => p.id === parseInt(id));
};

export const getProductBySlug = (slug) => {
  return mockProducts.find(p => p.slug === slug);
};

export const getProductsByCategory = (category) => {
  return mockProducts.filter(p => p.category === category);
};

export const getProductsBySubcategory = (subcategory) => {
  return mockProducts.filter(p => p.subcategory === subcategory);
};

export const getFeaturedProducts = () => {
  return mockProducts.filter(p => p.isHot || p.isBestSeller).slice(0, 8);
};

export const getNewProducts = () => {
  return [...mockProducts].sort((a, b) =>
    new Date(b.lastUpdate) - new Date(a.lastUpdate)
  ).slice(0, 8);
};

export const getBestSellingProducts = () => {
  return [...mockProducts].sort((a, b) => b.sold - a.sold).slice(0, 8);
};

// Filter products based on multiple criteria
export const filterProducts = (filters = {}) => {
  let filtered = [...mockProducts];

  // Filter by category
  if (filters.category) {
    filtered = filtered.filter(p => p.category === filters.category);
  }

  // Filter by technology
  if (filters.technology) {
    filtered = filtered.filter(p =>
      p.technology.some(t =>
        t.toLowerCase().includes(filters.technology.toLowerCase())
      )
    );
  }

  // Filter by features
  if (filters.features && filters.features.length > 0) {
    filtered = filtered.filter(p => {
      const productFeatures = p.features || [];
      return filters.features.some(feature =>
        productFeatures.some(pf =>
          pf.toLowerCase().includes(feature.toLowerCase())
        )
      );
    });
  }

  // Filter by search query
  if (filters.search) {
    const searchLower = filters.search.toLowerCase();
    filtered = filtered.filter(p =>
      p.name.toLowerCase().includes(searchLower) ||
      p.description.toLowerCase().includes(searchLower) ||
      p.categoryName.toLowerCase().includes(searchLower) ||
      p.technology.some(t => t.toLowerCase().includes(searchLower))
    );
  }

  // Filter by price range
  if (filters.minPrice !== undefined && filters.minPrice > 0) {
    filtered = filtered.filter(p => p.price >= filters.minPrice);
  }
  if (filters.maxPrice !== undefined && filters.maxPrice < 5000000) {
    filtered = filtered.filter(p => p.price <= filters.maxPrice);
  }

  // Filter by rating
  if (filters.rating) {
    filtered = filtered.filter(p => p.rating >= filters.rating);
  }

  // Sort products
  if (filters.sortBy) {
    switch (filters.sortBy) {
      case 'newest':
        filtered.sort((a, b) => new Date(b.lastUpdate) - new Date(a.lastUpdate));
        break;
      case 'price-low-high':
        filtered.sort((a, b) => a.price - b.price);
        break;
      case 'price-high-low':
        filtered.sort((a, b) => b.price - a.price);
        break;
      case 'rating':
        filtered.sort((a, b) => b.rating - a.rating);
        break;
      case 'popular':
        filtered.sort((a, b) => b.sold - a.sold);
        break;
      case 'name':
        filtered.sort((a, b) => a.name.localeCompare(b.name));
        break;
      default:
        // Default: newest first
        filtered.sort((a, b) => new Date(b.lastUpdate) - new Date(a.lastUpdate));
    }
  }

  return filtered;
};

export default mockProducts;
